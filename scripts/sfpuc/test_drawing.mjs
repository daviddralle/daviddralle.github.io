import assert from 'node:assert/strict';
import {geometryError,sessionError,toKML,expandMultipoints} from '../../field-sites/sfpuc/draw-export.mjs';
const polygon=ring=>({type:'Polygon',coordinates:[ring]});
const valid=polygon([[0,0],[1,0],[1,1],[0,1],[0,0]]);
assert.equal(geometryError(valid),'');
assert.equal(geometryError({type:'Point',coordinates:[-121.85,37.55]}),'');
assert.equal(geometryError({type:'LineString',coordinates:[[0,0],[1,1]]}),'');
for(const bad of [polygon([[0,0],[1,1],[1,0],[0,1],[0,0]]),polygon([[0,0],[1,0],[2,0],[0,0]]),polygon([[0,0],[1,0],[1,1]]),{type:'Point',coordinates:[Infinity,37]},{type:'LineString',coordinates:[[0,0],[0,0]]}]) assert.ok(geometryError(bad));
// Closing-edge crossings and nonadjacent touching vertices must also be rejected.
assert.ok(geometryError(polygon([[0,0],[2,0],[2,2],[0,2],[1,-1],[0,0]])));
assert.ok(geometryError(polygon([[0,0],[2,0],[2,2],[1,0],[0,2],[0,0]])));
const f={type:'Feature',properties:{id:'A & <1>',description:'α “oak”\n<notes> & soil',draw_type:'polygon'},geometry:valid};
assert.equal(sessionError([f]),'');assert.ok(sessionError([f,f]));
assert.ok(sessionError([{...f,properties:{id:' '}}]));
const source=JSON.stringify(f),kml=toKML([f],'Session & 1');
assert.match(kml,/<name>A &amp; &lt;1&gt;<\/name>/);
assert.match(kml,/<Data name="description"><value>α “oak”\n&lt;notes&gt; &amp; soil<\/value>/);
assert.match(kml,/<altitudeMode>clampToGround<\/altitudeMode>/);
assert.match(kml,/<href>files\/point.png<\/href>/);
assert.equal(JSON.stringify(f),source,'Export must not mutate source coordinates');
console.log('Drawing validation and KML export checks passed.');

const multipoint={type:'MultiPoint',coordinates:[[-121.85,37.55],[-121.851,37.552],[-121.852,37.553]]};
assert.equal(geometryError(multipoint),'');
assert.equal(geometryError({type:'MultiPoint',coordinates:[[-121.85,37.55]]}),'');
for(const coordinates of [[],[[181,37]],[[0,NaN]],[[1]],null])assert.ok(geometryError({type:'MultiPoint',coordinates}));
const points={type:'Feature',properties:{id:'Boreholes',description:'Potential locations',draw_type:'multipoint'},geometry:multipoint};
const original=JSON.stringify(points),pointsKML=toKML([points],'Borehole candidates');
assert.match(pointsKML,/<MultiGeometry>/);
assert.equal((pointsKML.match(/<Point>/g)||[]).length,3);
for(const [lng,lat] of multipoint.coordinates)assert.ok(pointsKML.includes(`<coordinates>${lng},${lat},0</coordinates>`));
assert.equal(JSON.stringify(points),original);
assert.equal(sessionError(JSON.parse(JSON.stringify([points]))),'');
console.log('Multipoint validation, session and KML export checks passed.');

const legacy={...points,properties:{...points.properties,uid:'old-uid',created:'2026-10-21',site:'sheep-camp'}};
const existing={type:'Feature',properties:{id:'Boreholes-2',uid:'existing',draw_type:'marker'},geometry:{type:'Point',coordinates:[-121,37]}};
let uid=0;
const legacySource=JSON.stringify([legacy,existing]);
const expanded=expandMultipoints([legacy,existing],()=>`new-${++uid}`);
assert.equal(expanded.length,4);
assert.equal(sessionError(expanded),'');
assert.equal(new Set(expanded.map(f=>f.properties.uid)).size,4);
assert.equal(expanded[0].properties.uid,'old-uid');
assert.deepEqual(expanded.slice(0,3).map(f=>f.geometry.coordinates),multipoint.coordinates);
assert.ok(expanded.slice(0,3).every(f=>f.properties.description==='Potential locations'&&f.properties.site==='sheep-camp'));
assert.equal(JSON.stringify([legacy,existing]),legacySource);
expanded[0].properties.description='BH-1 notes';
assert.equal(expanded[1].properties.description,'Potential locations');
const individualKML=toKML(expanded,'Boreholes');
assert.equal((individualKML.match(/<Placemark /g)||[]).length,4);
assert.ok(!individualKML.includes('<MultiGeometry>'));
assert.match(individualKML,/<description>BH-1 notes<\/description>/);
assert.deepEqual(expandMultipoints(expanded),expanded);
console.log('Per-point metadata, legacy migration, ID collisions and separate placemark export checks passed.');
