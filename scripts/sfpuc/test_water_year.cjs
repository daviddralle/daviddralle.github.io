const assert=require('node:assert/strict');
const W=require('../../field-sites/sfpuc/dashboard/water-year.js');
const weather=require('../../field-sites/sfpuc/dashboard/data/weather.json');
const series=W.build(weather.daily);
assert.equal(W.year('2026-09-30'),2026);
assert.equal(W.year('2026-10-01'),2027);
assert.equal(W.keys.length,366);
const current=W.compare(series,2027);
assert.equal(current.focus.end,'2026-10-15');
assert.equal(current.current.total,0);
assert.equal(current.eligible.length,6);
assert.equal(current.median,0);
assert(Math.abs(current.max-47.498)<1e-9);
assert(current.focus.points.slice(current.index+1).every(p=>p.total===null),'No future values, including non-leap February 29');
const incomplete=series.find(s=>s.year===2025);
assert.notEqual(incomplete.points[W.keys.indexOf('02-11')].total,null);
assert(incomplete.points.slice(W.keys.indexOf('02-12')).every(p=>p.total===null),'Never resume a cumulative series after missing rain');
assert.equal(W.compare(series,2026).eligible.length,4,'Exclude incomplete prior WY 2025 from full-year statistics');
assert.equal(W.compare(series,2021).median,null,'No invented baseline for the first year');
function daily(start,end){const rows=[];for(let d=new Date(start+'T00:00:00Z');d.toISOString().slice(0,10)<=end;d.setUTCDate(d.getUTCDate()+1))rows.push({date:d.toISOString().slice(0,10),precip_mm:1,precip_trace:false});return rows;}
const fixtures=W.build(daily('2022-10-01','2024-09-30'));
const feb29=W.keys.indexOf('02-29'),mar1=W.keys.indexOf('03-01');
assert.equal(fixtures[0].points[feb29].calendarGap,true);
assert.equal(fixtures[0].points[feb29].date,null);
assert.equal(fixtures[0].points[feb29].total,151);
assert.equal(fixtures[0].points[mar1].total,152);
assert.equal(fixtures[1].points[feb29].total,152);
assert.equal(fixtures[1].points[mar1].total,153);
assert.equal(fixtures[0].points.at(-1).total,365);
assert.equal(fixtures[1].points.at(-1).total,366);
assert.equal(W.median([1,5,3,7]),4);
console.log('Passed: WY rollover, same-date comparisons, zero median, missing-day propagation, future truncation, leap alignment, and baseline exclusions.');
